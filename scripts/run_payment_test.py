"""Run the MOCKED sale-to-cash flow end to end and write outputs/payment_test_log.md.

Usage: python scripts/run_payment_test.py
No provider, no sandbox, no money: every step runs against an in-memory mock ledger.
"""
from __future__ import annotations
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.approval_manager import ApprovalRequired  # noqa: E402
from services import delivery, payments, reconcile, refunds  # noqa: E402

PRODUCT, PRICE = "BriefBuilder — monthly plan (digital)", 12.00


def run(out_path: Path = ROOT / "outputs" / "payment_test_log.md") -> dict:
    s = payments.MockStore()
    checks = []

    def check(name, ok):
        checks.append((name, bool(ok)))

    a = payments.create_order(s, PRODUCT, PRICE, "buyer-001")
    b = payments.create_order(s, PRODUCT, PRICE, "buyer-002")
    c = payments.create_order(s, PRODUCT, PRICE, "buyer-003")
    d = payments.create_order(s, PRODUCT, PRICE, "buyer-004")

    try:
        delivery.deliver(s, d["id"])
        check("No delivery before payment", False)
    except ValueError:
        s.note(f"Delivery for {d['id']} refused — no confirmed payment")
        check("No delivery before payment", True)

    payments.record_payment_event(s, a["id"], "evt_1001")
    check("Payment triggers delivery", delivery.has_access(s, a["id"]))
    dup = payments.record_payment_event(s, a["id"], "evt_1001")
    check("Replayed event is idempotent (one payment, one delivery)",
          dup["duplicate"] and len(s.payments) == 1 and len(s.access) == 1)

    payments.record_payment_event(s, b["id"], "evt_1002")
    try:
        refunds.refund(s, b["id"], approved_by=None, reason="buyer request")
        check("Refund without founder approval is refused", False)
    except ApprovalRequired:
        check("Refund without founder approval is refused", True)
    refunds.refund(s, b["id"], approved_by="founder", reason="buyer request")
    check("Founder-approved refund revokes access", not delivery.has_access(s, b["id"]))

    payments.record_payment_event(s, c["id"], "evt_1003", amount=9.00)  # deliberate short payment
    check("Short payment is held, not delivered", not delivery.has_access(s, c["id"]))
    rec = reconcile.reconcile(s)
    check("Reconciliation flags the short payment", any(c["id"] in i for i in rec["issues"]))

    lines = [
        "# Payment test log — MOCKED",
        "",
        "> **MOCKED.** No payment provider, no sandbox, no card data; no money moved. Generated by "
        "`python scripts/run_payment_test.py` from `services/payments.py`, `delivery.py`, `refunds.py` "
        "and `reconcile.py`. Fees are an illustrative ASSUMPTION (2.9% + 0.30).",
        "",
        f"Run at {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        "",
        "## Checks",
        "",
        *[f"- {'PASS' if ok else 'FAIL'} — {name}" for name, ok in checks],
        "",
        "## Event log",
        "",
        *[f"{i}. {line}" for i, line in enumerate(s.log, 1)],
        "",
        "## Reconciliation (orders ↔ payments ↔ fees ↔ refunds ↔ payouts)",
        "",
        "| Order | Status | Price | Paid | Fee | Refunded | Payout | Access |",
        "|---|---|---|---|---|---|---|---|",
        *[f"| {r['order']} | {r['status']} | {r['price']:.2f} | {r['paid']:.2f} | {r['fee']:.2f} | "
          f"{r['refunded']:.2f} | {r['payout']:.2f} | {r['access']} |" for r in rec["rows"]],
        f"| **Total** | | | {rec['totals']['paid']:.2f} | {rec['totals']['fee']:.2f} | "
        f"{rec['totals']['refunded']:.2f} | {rec['totals']['payout']:.2f} | |",
        "",
        "Issues found: " + ("; ".join(rec["issues"]) if rec["issues"] else "none"),
        "",
    ]
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"[payment-test] {sum(ok for _, ok in checks)}/{len(checks)} checks passed -> {out_path}")
    return {"checks": checks, "reconcile": rec}


if __name__ == "__main__":
    result = run()
    sys.exit(0 if all(ok for _, ok in result["checks"]) else 1)
