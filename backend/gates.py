"""Gates — pure functions that turn a phase's evidence into a recommendation.

Every phase ends at a gate. The gate only RECOMMENDS one of GO / REPEAT / PIVOT / STOP; the founder
then chooses what actually happens (continue, repeat, pivot back or stop) in the UI, and that choice
is recorded with approved_by = founder. Nothing advances without it (backend/approval.py).
"""
from __future__ import annotations

OUTCOMES = ("GO", "REPEAT", "PIVOT", "STOP")

# Founder choices at a gate, and the recommendation each one follows.
CHOICES = {"continue": "GO", "repeat": "REPEAT", "pivot": "PIVOT", "stop": "STOP"}

# Where "pivot back" goes: the previous phase (Discover pivots onto itself with a reframed idea).
PIVOT_TARGET = {"discover": "discover", "validate": "discover", "build": "validate",
                "commercial": "build", "launch": "commercial", "operate": "launch"}

# Pre-set evidence threshold for the (MOCKED) landing-page demand test, fixed BEFORE the test runs.
WAITLIST_TARGET = {"signups": 100, "days": 14}


def discover_gate(feasibility: dict) -> str:
    """Feasibility agent's verdict on sourced research; anything unrecognised means gather more."""
    rec = str((feasibility or {}).get("gate_recommendation", "")).upper()
    return rec if rec in OUTCOMES else "REPEAT"


def validate_gate(assessments: list[dict]) -> str:
    """Riskiest assumptions vs. web evidence: mostly contradicted → PIVOT, clean support → GO."""
    if not assessments:
        return "REPEAT"
    contradicted = sum(a.get("verdict") == "contradicted" for a in assessments)
    supported = sum(a.get("verdict") == "supported" for a in assessments)
    if contradicted * 2 >= len(assessments):
        return "PIVOT"
    if contradicted == 0 and supported >= 1:
        return "GO"
    return "REPEAT"


def build_gate(checks_passed: bool, n_features: int) -> str:
    """Passing tests: every automated prototype check passes and at least 3 MVP features exist."""
    return "GO" if checks_passed and n_features >= 3 else "REPEAT"


def commercial_gate(gross_margin_pct: float) -> str:
    """Pre-set threshold: gross margin above 20%."""
    try:
        return "GO" if float(gross_margin_pct) > 20 else "REPEAT"
    except (TypeError, ValueError):
        return "REPEAT"


def launch_gate(unsupported_claims: list) -> str:
    """No marketing claim may go out without evidence."""
    return "GO" if not unsupported_claims else "REPEAT"


def operate_gate() -> str:
    """Final phase: the persevere-or-pivot memo is the output; the founder decides what's next."""
    return "GO"


def waitlist_gate(actual: int, target: int = WAITLIST_TARGET["signups"]) -> dict:
    """Demand-test gate on REAL sign-ups the founder reports (never generated by the system).

    ≥ 100% of target → GO; ≥ 50% → REPEAT (iterate the page/offer); ≥ 20% → PIVOT; below → STOP.
    Example: target 100 in 14 days, got 12 → 12% → STOP, instead of spinning the result.
    """
    actual, target = max(int(actual), 0), max(int(target), 1)
    ratio = actual / target
    if ratio >= 1:
        outcome = "GO"
    elif ratio >= 0.5:
        outcome = "REPEAT"
    elif ratio >= 0.2:
        outcome = "PIVOT"
    else:
        outcome = "STOP"
    return {"outcome": outcome, "actual": actual, "target": target,
            "days": WAITLIST_TARGET["days"], "ratio": round(ratio, 3),
            "rationale": (f"{actual} real sign-ups against a pre-set target of {target} in "
                          f"{WAITLIST_TARGET['days']} days ({ratio:.0%}). Recommendation: {outcome}.")}
